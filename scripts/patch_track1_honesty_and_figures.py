def insert_picture(para, path: Path, width_cm: float = 15.4) -> None:
    _wipe_runs(para._p)
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run()
    run.add_picture(str(path), width=Cm(width_cm))


