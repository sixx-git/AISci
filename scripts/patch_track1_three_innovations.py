def patch_huizong(doc: Document) -> int:
    answers = {}
    for full in PARAS.values():
        for label in KNOWN_LABELS:
            if full.startswith(label):
                answers[label] = full[len(label):]
                break
    answers.update({
        "参赛作品简介（300字内）：": INTRO_300,
        "参赛作品简介：": INTRO_300,
        "R3 参赛作品简介：": INTRO_300,
        "Qwen及AI技术说明（300字内）：": QWEN_300,
        "R4 Qwen及AI技术说明：": QWEN_300,
        "核心主张·具体问题：": PARAS[10].split("：", 1)[1],
        "核心主张·核心方法：": PARAS[11].split("：", 1)[1],
        "核心主张·结果2：": PARAS[13].split("：", 1)[1],
    })
    n = 0
    for p in doc.paragraphs:
        raw = "".join((r.text or "") for r in p.runs)
        if raw.startswith("====") or not raw.strip():
            continue
        for label, answer in answers.items():
            if label in raw[:80]:
                head = raw.split(label, 1)[0] + label
                set_fill(p, head + answer)
                n += 1
                break
    return n


def main() -> None:
    for name, text in (("简介", INTRO_300), ("Qwen说明", QWEN_300)):
        n = zh_len(text)
        print(name, n)
        if n > 300:
            raise SystemExit(f"{name} 超 300: {n}")

    doc = Document(str(TPL))
    set_cell(doc.tables[0].rows[3].cells[1], INTRO_300)
    set_cell(doc.tables[0].rows[4].cells[1], QWEN_300)
    for idx, text in PARAS.items():
        set_fill(doc.paragraphs[idx], text)
    for (ti, ri, ci), val in CELLS.items():
        set_cell(doc.tables[ti].rows[ri].cells[ci], val)
    doc.save(str(TPL))
    print("template saved")

    hz = Document(str(HZ))
    n = patch_huizong(hz)
    hz.save(str(HZ))
    print("huizong", n)


if __name__ == "__main__":
    main()
