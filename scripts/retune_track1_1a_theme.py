def set_fill(para, text: str) -> None:
    """Write fill-in text: prompt label without underline, answer underlined."""
    _wipe_runs(para._p)
    label = next((x for x in KNOWN_LABELS if text.startswith(x)), "")
    if not label:
        for x in KNOWN_LABELS:
            pos = text.find(x)
            if 0 <= pos <= 20:
                head, label = text[:pos], x
                answer = text[pos + len(x) :]
                if head:
                    para._p.append(_make_run(head, underline=False))
                para._p.append(_make_run(label, underline=False))
                if answer:
                    para._p.append(_make_run(answer, underline=True))
                return
        style = para.style.name if para.style else ""
        if style.startswith("List") and "：" in text:
            i = text.find("：")
            label, answer = text[: i + 1], text[i + 1 :]
            para._p.append(_make_run(label, underline=False))
            if answer:
                para._p.append(_make_run(answer, underline=True))
            return
        para._p.append(_make_run(text, underline=True))
        return
    answer = text[len(label) :]
    para._p.append(_make_run(label, underline=False))
    if answer:
        para._p.append(_make_run(answer, underline=True))


def set_cell(cell, text: str) -> None:
    p = cell.paragraphs[0]
    _wipe_runs(p._p)
    if text:
        p._p.append(_make_run(text, underline=False))
    for extra in cell.paragraphs[1:]:
        _wipe_runs(extra._p)


def zh_len(s: str) -> int:
    return len(s.replace(" ", "").replace("\n", ""))


