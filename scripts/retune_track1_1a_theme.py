def patch_huizong(doc: Document) -> int:
    answers_by_label = {}
    for full in PARAS.values():
        for label in KNOWN_LABELS:
            if full.startswith(label):
                answers_by_label[label] = full[len(label) :]
                break
    answers_by_label["一项真实中间结果示例："] = PARAS[73]
    answers_by_label["筛选结果如何形成："] = PARAS[85]
    n = 0
    for p in doc.paragraphs:
        raw = "".join((r.text or "") for r in p.runs)
        if raw.startswith("====") or not raw.strip():
            continue
        for label, answer in answers_by_label.items():
            if label in raw[:120]:
                prefix = raw.split(label, 1)[0] + label
                set_fill(p, prefix + answer)
                n += 1
                break
    return n


